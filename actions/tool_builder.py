"""
Scaffold and register new Lucas tools (action modules or lightweight custom scripts).

Full action modules: actions/<name>.py + tool_registry entry (survives restart).
Custom scripts: memory/custom_tools/ (no code in actions/, reconnect to use in voice).
"""

from __future__ import annotations

import re
import textwrap

from memory.config_manager import get_base_dir
from memory.custom_tools import loader as custom_loader

from core.logger import get_logger

logger = get_logger(__name__)

BASE_DIR = get_base_dir()
_ACTIONS_DIR = BASE_DIR / "actions"
_NAME_RE = re.compile(r"^[a-z][a-z0-9_]{1,30}$")

_MODULE_TEMPLATE = '''"""
{description}
"""

TOOL_SCHEMA = {{
    "name": "{name}",
    "description": "{description}",
    "parameters": {{
        "type": "OBJECT",
        "properties": {{
            "query": {{"type": "STRING", "description": "Input for this tool"}},
        }},
        "required": [],
    }},
}}


def {name}(
    parameters: dict,
    response=None,
    player=None,
    session_memory=None,
    speak=None,
) -> str:
    params = parameters or {{}}
    query = (params.get("query") or "").strip()
    if not query:
        return "Please provide a query parameter, sir."
    # TODO: implement — generated by tool_builder
    return f"{{name}} received: {{query}}"
'''


TOOL_SCHEMA = {
    "name": "tool_builder",
    "description": (
        "Create or register new tools for Lucas. "
        "create_custom (fast script) | create_module (full action) | register | list."
    ),
    "parameters": {
        "type": "OBJECT",
        "properties": {
            "action": {
                "type": "STRING",
                "description": "list | status | create_custom | create_module | register",
            },
            "name": {"type": "STRING", "description": "snake_case tool name"},
            "description": {"type": "STRING", "description": "What the tool does"},
            "logic": {
                "type": "STRING",
                "description": (
                    "create_custom: Python body inside main() after params is loaded, "
                    "must return a string. Example: return params.get('query','')"
                ),
            },
            "accepts_speak": {
                "type": "BOOLEAN",
                "description": "create_module: pass True if tool should use speak=",
            },
        },
        "required": ["action"],
    },
}


def _validate_name(name: str) -> str | None:
    name = (name or "").strip().lower()
    if not _NAME_RE.match(name):
        return "Invalid name — use snake_case (e.g. summarize_file), 2–31 chars."
    reserved = {
        "tool_builder", "coding_workspace", "self_improve", "agent_task",
        "shutdown_lucas", "save_memory",
    }
    if name in reserved:
        return f"Name {name!r} is reserved."
    return None


def tool_builder(
    parameters: dict,
    response=None,
    player=None,
    session_memory=None,
    speak=None,
) -> str:
    import agent.tool_registry as registry

    p = parameters or {}
    action = (p.get("action") or "list").lower().strip()
    name = (p.get("name") or "").strip().lower()
    desc = (p.get("description") or "").strip() or f"Custom tool {name}"
    logic = (p.get("logic") or "").strip()
    accepts_speak = bool(p.get("accepts_speak", False))

    if action == "list":
        names = registry.list_tool_names()
        manifest = custom_loader._load_manifest().get("tools", [])
        custom_names = [t.get("name") for t in manifest if isinstance(t, dict)]
        lines = [
            f"Registered tools ({len(names)}):",
            ", ".join(names[:40]) + ("…" if len(names) > 40 else ""),
        ]
        if custom_names:
            lines.append(f"Custom manifest: {', '.join(custom_names)}")
        lines.append(
            "Reconnect voice after creating a tool so Live API sees new declarations."
        )
        return "\n".join(lines)

    if action == "status":
        return (
            f"actions_dir: {_ACTIONS_DIR}\n"
            f"custom_tools: {custom_loader.CUSTOM_DIR}\n"
            f"registered: {len(registry.list_tool_names())}"
        )

    err = _validate_name(name)
    if err and action not in ("list", "status"):
        return err

    if action == "create_custom":
        body = logic or textwrap.dedent(
            """
            query = (params.get("query") or "").strip()
            return f"{name} says: " + (query or "ready")
            """
        ).strip()
        try:
            compile(body, f"<{name}>", "exec")
        except SyntaxError as e:
            return f"Invalid logic syntax: {e}"

        msg = custom_loader.add_custom_tool(name, desc, body)
        custom_loader.register_custom_tools(registry.register)
        return f"{msg}\nActive in this process. Reconnect voice to expose to Live API."

    if action == "create_module":
        module_path = f"actions.{name}"
        file_path = _ACTIONS_DIR / f"{name}.py"
        if file_path.exists():
            return f"Module already exists: {file_path}. Use action=register."

        file_path.write_text(
            _MODULE_TEMPLATE.format(name=name, description=desc.replace('"', "'")),
            encoding="utf-8",
        )
        added = registry.ensure_action_module_entry(module_path, name, accepts_speak)
        try:
            tool_name = registry.register_module(module_path, name, accepts_speak=accepts_speak)
        except Exception as e:
            return f"Wrote {file_path} but register failed: {e}"

        parts = [f"Created action module actions/{name}.py", f"Registered as tool: {tool_name}"]
        if added:
            parts.append("Added to agent/tool_registry.py _ACTION_MODULES (persists).")
        parts.append("Reconnect voice session to use with Live API.")
        return "\n".join(parts)

    if action == "register":
        file_path = _ACTIONS_DIR / f"{name}.py"
        if not file_path.is_file():
            return f"No module at actions/{name}.py — use create_module first."
        module_path = f"actions.{name}"
        registry.ensure_action_module_entry(module_path, name, accepts_speak)
        try:
            tool_name = registry.register_module(module_path, name, accepts_speak=accepts_speak)
        except Exception as e:
            return f"Register failed: {e}"
        return f"Registered {tool_name}. Reconnect voice to expose to Live API."

    return "Unknown action. Use list, status, create_custom, create_module, or register."
